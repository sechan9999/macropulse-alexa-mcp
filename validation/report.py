"""
validation/report.py — docs/validation/report.md from validation/results/*/summary.json.

Every number in the report is read from the result files; the conclusions follow the decision rules in
docs/validation/preregistration.md (5% after a Holm correction over the five primary tests).
"""
from __future__ import annotations

import subprocess

from validation import stats
from validation.data import ROOT, read_manifest
from validation.results import load_json

OUT = ROOT / "docs" / "validation" / "report.md"


def _f(x, d=3, pct=False):
    if x is None:
        return "not computed"
    return f"{x * 100:.{d}f}%" if pct else f"{x:.{d}f}"


def _commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except Exception:
        return "unknown"


def primary_pvalues(s2, s3, s4, s5, s6) -> dict:
    p = {}
    if s3:
        p["H1 regime"] = s3["h1"]["p_value"]
    if s2 and s2["goyal_welch"]["pass"]:
        p["H2 expected return"] = s2["full"]["clark_west"]["p_one_sided"]
    if s4:
        p["H3 strategy"] = 1 - s4["full"]["dsr"]["dsr"]
    if s5:
        p["H4 VaR (95%)"] = s5["gaussian"]["var95"]["kupiec"]["p_value"]
    if s6:
        p["H5 DCF"] = s6["h5"]["p_one_sided"]
    return p


def write() -> str:
    s1, s2, s3, s4, s5, s6 = (load_json(f"stage{i}", "summary") for i in range(1, 7))
    pv = primary_pvalues(s2, s3, s4, s5, s6)
    adj = stats.holm(pv)
    L = ["# MacroPulse validation report", "",
         f"Generated by `python -m validation.run report` at commit `{_commit()}` from `validation/results/`. "
         "Rules: [`preregistration.md`](preregistration.md). Raw inputs: `validation/data/raw/manifest.json` "
         f"({len(read_manifest())} files pinned by SHA-256).", ""]

    L += ["## Primary tests (Holm-corrected over the five)", "",
          "| Hypothesis | Test | Raw p | Holm p | Conclusion |", "|---|---|---|---|---|"]

    def concl(name, rule):
        if name not in pv:
            return "not decidable"
        return rule(adj[name])
    rows = [
        ("H1 regime", "Risk-Off minus Risk-On log realised vol, one-sided bootstrap",
         lambda a: "significant effect" if a < 0.05 else "no effect"),
        ("H2 expected return", "Clark-West vs prevailing mean, NW(12), one-sided",
         lambda a: "significant effect" if a < 0.05 else "no effect"),
        ("H3 strategy", "Deflated Sharpe Ratio, N = 32 (p = 1 - DSR)",
         lambda a: "significant effect" if a < 0.05 else "no effect"),
        ("H4 VaR (95%)", "Kupiec POF, H0: 5% exceedances",
         lambda a: "miscalibrated (H0 rejected)" if a < 0.05 else "calibration not rejected"),
        ("H5 DCF", "mean yearly rank IC > 0, NW(1), one-sided",
         lambda a: "significant effect" if a < 0.05 else "no effect"),
    ]
    for name, test, rule in rows:
        extra = ""
        if name == "H2 expected return" and s2 and not s2["goyal_welch"]["pass"]:
            extra = " (pipeline check failed: see Stage 2)"
        L.append(f"| {name} | {test} | {_f(pv.get(name), 4)} | {_f(adj.get(name), 4)} | {concl(name, rule)}{extra} |")
    L.append("")

    if s1:
        L += ["## Stage 1. Data integrity", "",
              f"* Manifest: {s1['manifest_files']} files; problems: {s1['manifest_problems'] or 'none'}.",
              f"* Schema checks: {s1['schema']['sources']} sources; failed: {s1['schema']['failed_sources'] or 'none'}; "
              f"missing rate above limit: {s1['schema']['missing_rate_exceeded'] or 'none'}; "
              f"{s1['schema']['outliers_listed']} daily returns with |z| > 6 listed in `stage1/return_outliers.csv`.", "",
              "ALFRED release timing and revisions (observations first published after 1997):", "",
              "| Series | Median lag (days) | Max lag | Assumed lag | Published later than assumed | Revised | Mean abs revision |",
              "|---|---|---|---|---|---|---|"]
        for sid, r in s1["alfred"]["release_lags"].items():
            L.append(f"| {sid} | {_f(r['median_lag_days'], 0)} | {_f(r['max_lag_days'], 0)} | {r['assumed_lag_days']} | "
                     f"{_f(r['share_published_later_than_assumed'], 1, True)} | {_f(r['share_revised'], 1, True)} | "
                     f"{_f(r['mean_abs_revision'], 4)} |")
        L += ["", "Month-end values from `RELEASE_LAG_DAYS` on today's data vs the ALFRED value known at that month end:", "",
              "| Series | Months | Different | Mean abs difference |", "|---|---|---|---|"]
        for sid, r in s1["alfred"]["approximation"].items():
            L.append(f"| {sid} | {r['months_compared']} | {_f(r['share_different'], 1, True)} | {_f(r['mean_abs_difference'], 4)} |")
        L += ["", "The product model with today's credit spread vs the spread known at each month end (ALFRED):", "",
              "| Start | Regime label agreement | OOS R² (latest) | OOS R² (ALFRED) | Forecast correlation |",
              "|---|---|---|---|---|"]
        for k, r in s1["model_latest_vs_alfred"].items():
            L.append(f"| {k[-4:]} | {_f(r['regime_label_agreement'], 1, True)} | {_f(r['oos_r2_latest'], 2, True)} | "
                     f"{_f(r['oos_r2_alfred'], 2, True)} | {_f(r['forecast_correlation'], 3)} |")
        p = s1["prices"]
        L += ["", f"Prices: SPY total return vs Ken French market return, {p['months']} months ({p['first']} to {p['last']}): "
              f"{p['months_over_threshold']} months ({_f(p['share_over_threshold'], 0, True)}) differ by more than 5 bp "
              f"(listed in `stage1/spy_vs_kenfrench_over_5bp.csv`); mean {_f(p['mean_diff_bp'], 1)} bp, "
              f"sd {_f(p['sd_diff_bp'], 1)} bp, max {_f(p['max_abs_diff_bp'], 0)} bp, correlation {_f(p['correlation'], 4)}. "
              f"Cash rate (^IRX) vs Ken French RF: mean {_f(p['rf_mean_diff_bp'], 1)} bp, max {_f(p['rf_max_abs_diff_bp'], 0)} bp. "
              + p["note"], ""]

    if s2:
        g = s2["goyal_welch"]
        L += ["## Stage 2. Expected-return model (H2)", "",
              f"Pipeline check, {g['source']}: largest primary difference {_f(g['max_abs_diff_primary_pp'], 2)} pp "
              f"(tolerance {g['tolerance_pp']} pp): **{'pass' if g['pass'] else 'fail'}**. Table: `stage2/goyal_welch_replication.csv`.", ""]
        for lab in ("full", "product_2005"):
            r = s2[lab]
            cw, pt = r["clark_west"], r["pesaran_timmermann"]
            L.append(f"* {lab}: {r['n']} forecasts ({r['first_origin']} to {r['last_origin']}), OOS R² {_f(r['oos_r2'], 2, True)}, "
                     f"Clark-West t {_f(cw['stat'], 2)} (p {_f(cw['p_one_sided'], 4)}), sign hit rate {_f(pt['hit_rate'], 1, True)} "
                     f"vs {_f(pt['expected_by_chance'], 1, True)} by chance (p {_f(pt['p_one_sided'], 3)}).")
        L += ["", "| Period (full sample) | n | OOS R² | CW p |", "|---|---|---|---|"]
        for k, r in s2["full"]["subperiods"].items():
            L.append(f"| {k} | {r['n']} | {_f(r['oos_r2'], 2, True)} | {_f(r['cw_p'], 3)} |")
        lk = s2["leakage"]
        L += ["", f"Leakage: noise test correlation {_f(lk['noise_correlation'], 3)} (must stay below "
              f"{lk['noise_threshold']}: {'pass' if lk['noise_correlation'] < lk['noise_threshold'] else 'fail'}); "
              f"permutation test p {_f(lk['permutation']['p_value'], 3)} over {lk['permutation']['n_permutations']} shuffles "
              f"(null mean {_f(lk['permutation']['null_mean'], 2, True)}, 95th pct {_f(lk['permutation']['null_p95'], 2, True)}); "
              "look-ahead placebo OOS R² by months of outcome seen: "
              + ", ".join(f"k={k}: {_f(v, 2, True)}" for k, v in lk["lookahead_placebo"].items()) + ".", ""]

    if s3:
        h = s3["h1"]
        L += ["## Stage 3. Regime score (H1)", "",
              f"Sample {s3['sample']['first']} to {s3['sample']['last']} ({s3['sample']['months']} months). "
              f"Risk-Off minus Risk-On mean log realised volatility over the next 21 sessions: {_f(h['difference'], 3)} "
              f"(95% CI {_f(h['ci95'][0], 3)} to {_f(h['ci95'][1], 3)}; one-sided p {_f(h['p_value'], 4)}; "
              f"{h['n_a']} Risk-Off and {h['n_b']} Risk-On months). Since 2005: {_f(s3['h1_product_2005']['difference'], 3)} "
              f"(p {_f(s3['h1_product_2005']['p_value'], 4)}); with the ALFRED spread: {_f(s3['h1_alfred_spread']['difference'], 3)} "
              f"(p {_f(s3['h1_alfred_spread']['p_value'], 4)}).",
              f"Next-month return, Risk-Off minus Risk-On: {_f(s3['next_return_off_minus_on']['difference'], 4)} "
              f"(two-sided p {_f(s3['next_return_off_minus_on']['p_value'], 3)}).", ""]
        n = s3["nber"]
        L += [f"NBER: hit rate (recession months labelled Risk-Off) {_f(n['hit_rate'], 1, True)}; false alarms (Risk-Off months "
              f"outside recessions) {_f(n['false_alarm_rate'], 1, True)}; {n['recessions_flagged']} of {len(n['recessions'])} "
              f"recessions had a Risk-Off month within 12 months of their start; median timing {_f(n['median_lead_months'], 0)} months "
              "(negative = the first Risk-Off month came after the recession began, i.e. the score lags).",
              f"HMM: BIC prefers {s3['hmm']['states_by_bic']} states, out-of-sample likelihood {s3['hmm']['states_by_test_loglik']}; "
              f"{_f(s3['hmm']['risk_off_in_hmm_stress_state'], 1, True)} of Risk-Off months fall in the HMM stress state.",
              "Sensitivity (difference, p): z-score warm-up " + "; ".join(
                  f"{k} m: {_f(v['difference'], 3)}, {_f(v['p_value'], 3)}" for k, v in s3["sensitivity"]["z_warmup"].items())
              + "; GMM components " + "; ".join(
                  f"{k}: {_f(v['difference_highest_minus_lowest_spread_component'], 3)}, {_f(v['p_value'], 3)}"
                  for k, v in s3["sensitivity"]["gmm"].items()) + ".", ""]

    if s4:
        r = s4["full"]
        d = r["dsr"]
        L += ["## Stage 4. Backtest overfitting (H3)", "",
              f"{r['months']} months ({r['first']} to {r['last']}), {r['n_rules']} rules. Default rule annualised Sharpe "
              f"{_f(d['sr_annual'], 2)}; expected maximum of {d['n_trials']} trials {_f(d['sr0_annual'], 2)}; "
              f"**DSR {_f(d['dsr'], 3)}** (PSR against 0: {_f(d['psr_vs_zero'], 3)}). PBO {_f(r['pbo']['pbo'], 3)} over "
              f"{r['pbo']['n_splits']} CSCV splits. The default ranks {r['default_rank_of_32_by_sharpe']} of 32 by Sharpe.",
              "SPA (consistent p, small = the strategy beats the benchmark): " + "; ".join(
                  f"{k}: {_f(v['p_consistent'], 3)}" for k, v in r["spa"].items()) + ".", "",
              "| Cost (bp) | Ann. return | Sharpe | Max drawdown |", "|---|---|---|---|"]
        for c, v in sorted(s4["cost_sensitivity"].items(), key=lambda kv: float(kv[0])):
            L.append(f"| {c} | {_f(v['ann_return'], 2, True)} | {_f(v['sharpe'], 2)} | {_f(v['max_drawdown'], 1, True)} |")
        L += ["", "| Execution | Ann. return | Sharpe |", "|---|---|---|"]
        order = ["same close (product)", "one session later", "one month later"]
        for k, v in sorted(s4["execution_delay"].items(), key=lambda kv: order.index(kv[0]) if kv[0] in order else 9):
            L.append(f"| {k} | {_f(v['ann_return'], 2, True)} | {_f(v['sharpe'], 2)} |")
        L.append("")

    if s5:
        L += ["## Stage 5. Risk model (H4)", "",
              "| Method | Conf. | Months | Exceed. | Expected | Kupiec p | Indep. p | ES Z2 | ES p | Basel |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for meth in ("gaussian", "bootstrap"):
            for c in (95, 99):
                v = s5[meth][f"var{c}"]
                k, ch, es = v["kupiec"], v["christoffersen"], v["es_test"]
                L.append(f"| {meth} | {c}% | {k['n']} | {k['exceedances']} | {_f(k['expected'], 1)} | {_f(k['p_value'], 4)} | "
                         f"{_f(ch['p_ind'], 3)} | {_f(es['z2'], 3)} | {_f(es['p_value'], 3)} | {v.get('basel', {}).get('zone', '-')} |")
        L.append("")

    if s6:
        h = s6["h5"]
        L += ["## Stage 6. DCF equity report (H5)", "",
              f"Inputs vs FSDS: {s6['inputs_vs_fsds']['items_checked']} items checked; "
              f"{len(s6['inputs_vs_fsds']['flagged_over_0_5pct'])} flagged (> 0.5% or not found); details in "
              "`stage6/inputs_vs_fsds.csv`.",
              f"Damodaran: latest implied ERP {_f(s6['damodaran']['implied_erp']['implied_erp'], 2, True)} "
              f"({s6['damodaran']['implied_erp']['year']}) vs the engine's {_f(s6['damodaran']['engine_erp'], 2, True)}; "
              "beta and WACC by company in `stage6/damodaran_comparison.csv`.",
              f"Extreme outputs among successful name-years: {s6.get('extreme_outputs')}.",
              f"Point-in-time panel: coverage {s6['coverage']}; {s6['errors']} name-years failed and are listed with "
              f"their error. Mean yearly rank IC {_f(h['mean_ic'], 3)} over {h['years']} years ({h['observations']} "
              f"observations), t {_f(h['t'], 2)}, one-sided p {_f(h['p_one_sided'], 3)}.", "",
              "| Year | n | Rank IC |", "|---|---|---|"]
        for y, v in h["yearly"].items():
            L.append(f"| {y} | {v['n']} | {_f(v['rank_ic'], 3)} |")
        L += ["", "| Rating | n | Mean 12m excess | Median |", "|---|---|---|---|"]
        for k, v in h["by_rating"].items():
            L.append(f"| {k} | {int(v['count'])} | {_f(v['mean'], 1, True)} | {_f(v['median'], 1, True)} |")
        L.append("")

    L += reading(s1, s2, s3, s4, s5, s6)
    errs = [f"stage{i}" for i in range(1, 7) if load_json(f"stage{i}", "error") and not load_json(f"stage{i}", "summary")]
    if errs:
        L += ["## Not computed", "", "These stages failed; their tracebacks are in `validation/results/<stage>/error.json`: "
              + ", ".join(errs) + ".", ""]
    text = "\n".join(L)
    OUT.write_text(text, encoding="utf-8")
    return text


def reading(s1, s2, s3, s4, s5, s6) -> list:
    """Limits and alternative readings next to each result (numbers come from the same result files)."""
    if not all((s1, s2, s3, s4, s5, s6)):
        return []
    g, h1, d, v99, h5 = s2["goyal_welch"], s3["h1"], s4["full"]["dsr"], s5["gaussian"]["var99"], s6["h5"]
    t = s2["goyal_welch"]
    return ["## Reading the results", "",
            "**H1, regime: significant effect.** After a Risk-Off month end the next month's realised volatility is "
            f"about {_f(2.718281828 ** h1['difference'], 1)}x that after a Risk-On month end, in every sub-sample and "
            "setting tried. Limits: the score includes trailing 12-month realised volatility, so part of this is "
            "volatility clustering; the credit spread's own contribution was not isolated (not pre-registered). The "
            "score is not a recession signal: it turns Risk-Off after recessions begin, and most Risk-Off months are "
            "outside recessions. The next-month return is not lower after Risk-Off (two-sided p "
            f"{_f(s3['next_return_off_minus_on']['p_value'], 3)}).", "",
            "**H2, expected return: not decidable under the pre-registered rule.** The pipeline check missed the "
            f"0.5 pp tolerance by {_f(t['max_abs_diff_primary_pp'] - t['tolerance_pp'], 2)} pp on one of six primary "
            "values (d/p, forecasts from 1965); the other five are within it. It needed two fixes after the first run, "
            "both to match the paper's own procedure: pre-1926 returns (absent from the current data file) and the "
            "paper's adjusted OOS R² (Equation 6; confirmed by its cay3 example). Descriptively the model loses to the "
            f"prevailing mean: OOS R² {_f(s2['full']['oos_r2'], 1, True)} since 1985 and "
            f"{_f(s2['product_2005']['oos_r2'], 1, True)} on the product's 2005 start, worse than the average model fitted "
            f"to shuffled returns ({_f(s2['leakage']['permutation']['null_mean'], 1, True)}). The leakage checks are clean. "
            "Until a pipeline fix passes the check, the product should not describe this forecast as informative.", "",
            f"**H3, strategy: no effect.** The Sharpe ratio is above zero on its own (PSR {_f(d['psr_vs_zero'], 2)}), but "
            f"not above the best of 32 rules expected by chance (DSR {_f(d['dsr'], 2)} < 0.95), and SPA finds no win over "
            "buy-and-hold, the 10-month trend rule or 60/40. Low PBO over 1960-2026 means the choice among the 32 rules "
            f"is not what failed; over 2005-2026 PBO is {_f(s4['product_2005']['pbo']['pbo'], 2)}.", "",
            f"**H4, VaR: 95% calibrated; 99% under-covers.** The 99% VaR was exceeded {v99['kupiec']['exceedances']} times "
            f"against {_f(v99['kupiec']['expected'], 1)} expected (Kupiec p {_f(v99['kupiec']['p_value'], 3)}, Basel "
            f"{v99['basel']['zone']}), and the expected shortfall is too small (Z2 p {_f(v99['es_test']['p_value'], 3)}): "
            "the normal model's tails are too thin. The bootstrap of daily returns does slightly better and is still yellow.", "",
            f"**H5, DCF: no effect.** The mean yearly rank IC is {_f(h5['mean_ic'], 3)} and the ratings do not order "
            "next-year excess returns. Limits: survivorship (companies that no longer map to an SEC CIK or Yahoo ticker "
            "drop out), a community constituent list, and the regime and market drift taken from today's data vintage. "
            f"{s6['extreme_outputs']['upside_above_500pct'] + s6['extreme_outputs']['upside_below_minus_95pct']} of "
            f"{s6['extreme_outputs']['name_years']} name-years give an upside above +500% or below -95%: negative fair "
            "values when FCFF is negative (airlines in 2020-21, utilities, AMZN 2021-22) and a share count far too small "
            "for FOX/FOXA. These are engine issues to fix in a new, separately scored model version.", "",
            "**Data.** BAA/AAA are published a median 3 days after month end, so the product's regime, which puts month "
            "m's Moody's average in row m, sees it a few days early. Using the values known at each month end changes "
            f"{_f(1 - s1['model_latest_vs_alfred']['start_1976']['regime_label_agreement'], 0, True)} of labels and the "
            "OOS R² by under 1 pp. CPI, unemployment and industrial production are revised often; that affects only "
            "the offline research pipeline (src/data_fred.py), which uses today's vintage.", ""]
